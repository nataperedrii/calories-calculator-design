// Build 02-design-system/index.standalone.html: the docs page with tokens.css, components.css
// and docs.css inlined, and every local image embedded as a data URI (photos downscaled to
// 800 px with a Chromium canvas). It renders correctly without any sibling files.
// Google Fonts stays external; the font stacks have offline fallbacks.
//   npm run build:standalone
import { chromium } from "playwright";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname, extname } from "node:path";
import { fileURLToPath } from "node:url";

const DS = resolve(dirname(fileURLToPath(import.meta.url)), "..");
let html = readFileSync(resolve(DS, "index.html"), "utf8");

const browser = await chromium.launch();
const page = await browser.newPage();
const cache = new Map();

/** Local asset → data URI. JPEGs are downscaled to 800 px wide; SVGs are embedded as-is. */
async function dataUri(relPath, fromDir) {
  const abs = resolve(fromDir, relPath);
  if (cache.has(abs)) return cache.get(abs);
  const bytes = readFileSync(abs);
  let uri;
  if (extname(abs) === ".svg") {
    uri = "data:image/svg+xml;base64," + bytes.toString("base64");
  } else {
    const src = "data:image/jpeg;base64," + bytes.toString("base64");
    uri = await page.evaluate(async (s) => {
      const img = new Image();
      img.src = s;
      await img.decode();
      const w = Math.min(800, img.naturalWidth);
      const h = Math.round((img.naturalHeight * w) / img.naturalWidth);
      const c = document.createElement("canvas");
      c.width = w;
      c.height = h;
      c.getContext("2d").drawImage(img, 0, 0, w, h);
      return c.toDataURL("image/jpeg", 0.82);
    }, src);
  }
  cache.set(abs, uri);
  return uri;
}

async function replaceAsync(str, re, fn) {
  const parts = [];
  let last = 0;
  for (const m of str.matchAll(re)) {
    parts.push(str.slice(last, m.index), await fn(...m));
    last = m.index + m[0].length;
  }
  parts.push(str.slice(last));
  return parts.join("");
}

try {
  // 1. inline local stylesheets (order preserved: tokens → components → docs)
  html = await replaceAsync(html, /<link rel="stylesheet" href="\.\/([\w-]+\.css)">/g, async (_m, file) => {
    let css = readFileSync(resolve(DS, file), "utf8");
    css = await replaceAsync(css, /url\("([^"]+)"\)/g, async (_u, p) => `url("${await dataUri(p, DS)}")`);
    return `<style data-source="${file}">\n${css}</style>`;
  });
  // 2. embed <img src="../…"> assets
  html = await replaceAsync(html, /<img src="(\.\.\/[^"]+)"/g, async (_m, p) => `<img src="${await dataUri(p, DS)}"`);
  // 3. mark the file as generated
  html = html.replace("<head>", "<head>\n  <!-- GENERATED by 02-design-system/tools/build-standalone.mjs from index.html. Styles and images are inlined. -->");
  writeFileSync(resolve(DS, "index.standalone.html"), html);
  console.log(`index.standalone.html ${(html.length / 1024).toFixed(0)} KB, ${cache.size} assets embedded`);
} finally {
  await browser.close();
}
